import { cookies } from "next/headers";

// Language chosen with the EN/ES switch; otherwise the fallback (e.g. the artist's preference).
export async function getLang(fallback = "en") {
  const store = await cookies();
  const v = store.get("lang")?.value;
  if (v === "es" || v === "en") return v;
  return fallback === "es" ? "es" : "en";
}

// Pick the right language from an { en, es } pair.
export const pick = (lang, obj) => (obj ? obj[lang] ?? obj.en : "");

